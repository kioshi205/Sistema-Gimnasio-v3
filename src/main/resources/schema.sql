CREATE TABLE IF NOT EXISTS PLAN (
                                    id_plan INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    nombre_plan VARCHAR(80) NOT NULL,
    precio_base DECIMAL(8,2) NOT NULL,
    duracion_dias INT NOT NULL,
    CONSTRAINT chk_plan_precio CHECK (precio_base >= 0),
    CONSTRAINT chk_plan_duracion CHECK (duracion_dias > 0)
    );

CREATE TABLE IF NOT EXISTS CATEGORIA (
                                         id_categoria INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         nombre_categoria VARCHAR(60) NOT NULL,
    descripcion VARCHAR(200),
    estado VARCHAR(10) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT chk_categoria_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
    );

CREATE TABLE IF NOT EXISTS SUBPRODUCTO (
                                           id_subproducto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           id_categoria INT NOT NULL,
                                           nombre_subproducto VARCHAR(100) NOT NULL,
    precio_individual DECIMAL(8,2) NOT NULL,
    estado VARCHAR(10) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT fk_subproducto_categoria FOREIGN KEY (id_categoria) REFERENCES CATEGORIA(id_categoria),
    CONSTRAINT chk_subproducto_precio CHECK (precio_individual >= 0),
    CONSTRAINT chk_subproducto_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
    );

CREATE TABLE IF NOT EXISTS PLAN_SUBPRODUCTO (
                                                id_plan_subproducto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                id_plan INT NOT NULL,
                                                id_subproducto INT NOT NULL,
                                                CONSTRAINT fk_ps_plan FOREIGN KEY (id_plan) REFERENCES PLAN(id_plan),
    CONSTRAINT fk_ps_subproducto FOREIGN KEY (id_subproducto) REFERENCES SUBPRODUCTO(id_subproducto),
    CONSTRAINT uq_plan_subproducto UNIQUE (id_plan, id_subproducto)
    );

CREATE TABLE IF NOT EXISTS CLIENTE (
                                       id_cliente INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       dni VARCHAR(8) NOT NULL UNIQUE,
    nombre VARCHAR(60) NOT NULL,
    apellido VARCHAR(80) NOT NULL,
    telefono VARCHAR(9),
    email VARCHAR(100) UNIQUE
    );

CREATE TABLE IF NOT EXISTS CUPON (
                                     id_cupon INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     codigo VARCHAR(30) NOT NULL UNIQUE,
    descripcion VARCHAR(150) NOT NULL,
    porcentaje_descuento INT NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    estado VARCHAR(15) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT chk_cupon_porcentaje CHECK (porcentaje_descuento > 0 AND porcentaje_descuento <= 100),
    CONSTRAINT chk_cupon_fechas CHECK (fecha_fin >= fecha_inicio),
    CONSTRAINT chk_cupon_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
    );

CREATE TABLE IF NOT EXISTS SUSCRIPCION (
                                           id_suscripcion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           id_cliente INT NOT NULL,
                                           id_plan INT,
                                           id_cupon INT,
                                           detalle VARCHAR(600) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    monto_total DECIMAL(8,2) NOT NULL,
    CONSTRAINT fk_suscripcion_cliente FOREIGN KEY (id_cliente) REFERENCES CLIENTE(id_cliente),
    CONSTRAINT fk_suscripcion_plan FOREIGN KEY (id_plan) REFERENCES PLAN(id_plan),
    CONSTRAINT fk_suscripcion_cupon FOREIGN KEY (id_cupon) REFERENCES CUPON(id_cupon),
    CONSTRAINT chk_suscripcion_fechas CHECK (fecha_fin > fecha_inicio),
    CONSTRAINT chk_suscripcion_monto CHECK (monto_total >= 0)
    );

CREATE TABLE IF NOT EXISTS MARCACION_ACCESO (
                                                id_acceso INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                id_cliente INT NOT NULL,
                                                id_suscripcion INT,
                                                fecha_acceso DATE NOT NULL,
                                                hora_acceso TIME NOT NULL,
                                                resultado VARCHAR(15) NOT NULL,
    CONSTRAINT fk_acceso_cliente FOREIGN KEY (id_cliente) REFERENCES CLIENTE(id_cliente),
    CONSTRAINT fk_acceso_suscripcion FOREIGN KEY (id_suscripcion) REFERENCES SUSCRIPCION(id_suscripcion),
    CONSTRAINT chk_acceso_resultado CHECK (resultado IN ('PERMITIDO', 'DENEGADO'))
    );